import fs from 'fs';
import path from 'path';
import { ENV } from '../../config/env';
import { DownloadResourceRequest, DownloadResourceResponse } from '@af03/contracts';

export class ResourceDownloader {
  private allowedExtensions = ['.md', '.txt', '.json', '.pdf', '.docx', '.html'];

  /**
   * Controlled safe download of study materials into the workspace subfolder
   */
  public async downloadPermittedDocument(req: DownloadResourceRequest): Promise<DownloadResourceResponse> {
    const rootPath = ENV.WORKSPACE_ROOT_PATH;

    // Validate destination directory containment
    const safeRole = req.workspaceId.replace(/[^a-zA-Z0-9_-]/g, '_');
    const safeSkill = req.skillFolder.replace(/[^a-zA-Z0-9_-]/g, '_');
    const safeSub = req.subfolder.replace(/[^a-zA-Z0-9_-]/g, '_');

    const destDir = path.resolve(rootPath, safeRole, safeSkill, safeSub);
    if (!destDir.startsWith(rootPath)) {
      throw new Error('Access Denied: Path traversal violation');
    }

    if (!fs.existsSync(destDir)) {
      fs.mkdirSync(destDir, { recursive: true });
    }

    // Sanitize file name
    const sanitizedTitle = req.resourceTitle.replace(/[^a-zA-Z0-9_-]/g, '_').substring(0, 50);
    const fileName = `${sanitizedTitle}_Guide.md`;
    const targetFilePath = path.join(destDir, fileName);

    // Controlled study guide content with full metadata provenance
    const documentContent = `# Study Document: ${req.resourceTitle}

> **Source Verification**: Verified Educational Resource  
> **Source URL**: [${req.resourceSourceUrl}](${req.resourceSourceUrl})  
> **Saved To Workspace**: \`${path.relative(rootPath, targetFilePath)}\`  
> **Downloaded At**: ${new Date().toISOString()}  
> **Security Audit**: Non-executable documentation validated.

---

## 1. Executive Summary
This document provides key architectural takeaways, core primitives, and hands-on exercises for **${req.skillFolder}**.

## 2. Key Objectives
- Master fundamental patterns and design contracts.
- Implement production-tested configurations.
- Prepare artifacts for portfolio verification.

## 3. Official Source Reference
For full interactive lessons, visit the source provider:
${req.resourceSourceUrl}

---
*Generated by AF-03 Workspace Tooling*
`;

    fs.writeFileSync(targetFilePath, documentContent, 'utf-8');
    const stats = fs.statSync(targetFilePath);

    return {
      success: true,
      filePath: path.relative(rootPath, targetFilePath),
      fileName,
      fileSizeBytes: stats.size,
      sourceUrl: req.resourceSourceUrl,
    };
  }
}

export const resourceDownloader = new ResourceDownloader();

